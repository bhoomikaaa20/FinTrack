import mongoose, { Document } from "mongoose";

export interface ITransaction extends Document {
    user: string;
    amount: number;
    type: "income" | "expense";
    category: string;
    date: Date;
    status: "normal" | "high";
    description: String,
    file_url: String,
    recurring?: mongoose.Types.ObjectId;
}

const transactionSchema = new mongoose.Schema({
    user: { type: mongoose.Schema.Types.ObjectId, ref: "User" },
    amount: Number,
    type: { type: String, enum: ["income", "expense"] },
    category: String,
    date: Date,
    description: String,
    file_url: String,
    status: { type: String, enum: ["normal", "high"], default: "normal" },
    // Set when the transaction was generated by a recurring rule
    recurring: { type: mongoose.Schema.Types.ObjectId, ref: "Recurring" },
});

export default mongoose.model<ITransaction>("Transaction", transactionSchema);